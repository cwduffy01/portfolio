// Converts the outlined logo (assets/logo.png) into a filled dot-matrix grid.
// Run with: node scripts/logo-to-dots.mjs [step]
// Output: lib/logoDots.ts (regenerate whenever the logo or step changes).

import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const SRC = "assets/logo.png";
const OUT = "lib/logoDots.ts";
// Grid pitch in source pixels. Smaller = more dots and finer detail.
const STEP = Number(process.argv[2] ?? 7);

const { data, info } = await sharp(SRC)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;

// 1. Stroke mask: dark, opaque pixels.
const ink = new Uint8Array(W * H);
for (let i = 0; i < W * H; i++) {
  const [r, g, b, a] = data.subarray(i * 4, i * 4 + 4);
  const darkness = (a / 255) * (1 - (0.299 * r + 0.587 * g + 0.114 * b) / 255);
  ink[i] = darkness > 0.25 ? 1 : 0;
}

// 2. Dilate strokes by 1px so anti-aliased gaps at sharp tips don't leak the fill.
const wall = new Uint8Array(W * H);
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    if (!ink[y * W + x]) continue;
    for (let dy = -1; dy <= 1; dy++) {
      for (let dx = -1; dx <= 1; dx++) {
        const nx = x + dx;
        const ny = y + dy;
        if (nx >= 0 && nx < W && ny >= 0 && ny < H) wall[ny * W + nx] = 1;
      }
    }
  }
}

// 3. Flood-fill the background from the image border. Whatever the flood
//    can't reach is enclosed by a stroke, i.e. part of the filled logo.
const outside = new Uint8Array(W * H);
const stack = [];
const push = (x, y) => {
  const i = y * W + x;
  if (!wall[i] && !outside[i]) {
    outside[i] = 1;
    stack.push(i);
  }
};
for (let x = 0; x < W; x++) { push(x, 0); push(x, H - 1); }
for (let y = 0; y < H; y++) { push(0, y); push(W - 1, y); }
while (stack.length) {
  const i = stack.pop();
  const x = i % W;
  const y = (i - x) / W;
  if (x > 0) push(x - 1, y);
  if (x < W - 1) push(x + 1, y);
  if (y > 0) push(x, y - 1);
  if (y < H - 1) push(x, y + 1);
}

// 4. Sample the filled shape on a grid: a cell gets a dot if it's mostly inside.
const cols = Math.ceil(W / STEP);
const rows = Math.ceil(H / STEP);
const dots = [];
for (let r = 0; r < rows; r++) {
  for (let c = 0; c < cols; c++) {
    let inside = 0;
    let total = 0;
    for (let y = r * STEP; y < Math.min((r + 1) * STEP, H); y++) {
      for (let x = c * STEP; x < Math.min((c + 1) * STEP, W); x++) {
        total++;
        if (!outside[y * W + x]) inside++;
      }
    }
    if (inside / total >= 0.5) dots.push([c, r]);
  }
}

const body = dots.map(([c, r]) => `[${c},${r}]`).join(",");
await writeFile(
  OUT,
  `// Generated by scripts/logo-to-dots.mjs — do not edit by hand.
export const LOGO_DOTS = {
  cols: ${cols},
  rows: ${rows},
  dots: [${body}] as [number, number][],
};
`,
);
console.log(`${dots.length} dots on a ${cols}x${rows} grid -> ${OUT}`);
